def seed_all(db):
    db.exec("INSERT IGNORE INTO company (id, name) VALUES (1, '我的公司')")
    db.exec_many("INSERT IGNORE INTO accounts (code, name, parent, level, nature, is_cash, cf_section, partner_kind, "
                 "currency) VALUES (%(code)s, %(name)s, %(parent)s, %(level)s, %(nature)s, %(is_cash)s, "
                 "%(cf_section)s, %(partner_kind)s, %(currency)s)", account_rows())
    for name, vtype, memo, lines in TEMPLATES:
        tid = db.exec("INSERT IGNORE INTO templates (name, v_type, memo) VALUES (%s, %s, %s)", (name, vtype, memo))
        if tid:
            db.exec_many("INSERT INTO template_lines (tpl_id, line_no, account, side, summary, ratio) "
                         "VALUES (%s, %s, %s, %s, %s, %s)",
                         [(tid, i + 1, a, s, sm, r) for i, (a, s, sm, r) in enumerate(lines)])
    db.exec_many("INSERT IGNORE INTO phrases (text) VALUES (%s)", [(p,) for p in PHRASES])
    db.exec_many("INSERT IGNORE INTO currencies (code, name, rate, rate_date) VALUES (%s, %s, %s, CURDATE())",
                 CURRENCIES)
    db.exec_many("INSERT IGNORE INTO ratios (name, formula, unit, memo, sort) VALUES (%s, %s, %s, %s, %s)",
                 [(n, f, u, m, i) for i, (n, f, u, m) in enumerate(RATIOS)])
    db.exec("INSERT IGNORE INTO departments (code, name) VALUES ('100', '管理部'), ('200', '業務部')")
