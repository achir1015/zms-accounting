def default_nature(code: str) -> str:
    if code[0] in "234":
        return "C"
    if code[:2] == "71" or code == "7":
        return "C"
    return "D"


def account_rows():
    for item in ACCOUNTS:
        code, name = item[0], item[1]
        opt = item[2] if len(item) > 2 else {}
        yield dict(code=code, name=name, parent=code[:-1], level=len(code),
                   nature=opt.get("n", default_nature(code)), is_cash=opt.get("cash", 0),
                   cf_section=opt.get("cf", "OP"), partner_kind=opt.get("pk", ""), currency=opt.get("cur", ""))


